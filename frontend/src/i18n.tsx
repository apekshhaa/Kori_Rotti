export interface TranslationContextValue {
  language: LanguageCode;
  setLanguage: (language: LanguageCode) => void;
  t: (key: string, fallback?: string) => string;
}

const defaultContext: TranslationContextValue = {
  language: 'en',
  setLanguage: () => {},
  t: (key: string, fallback = '') => fallback || key,
};

const TranslationContext = createContext<TranslationContextValue>(defaultContext);

const lookup = (obj: any, path: string): string | undefined => {
  return path.split('.').reduce((current, segment) => {
    if (current && typeof current === 'object' && segment in current) {
      return current[segment];
    }
    return undefined;
  }, obj) as string | undefined;
};

export const TranslationProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguage] = useState<LanguageCode>('en');

  const t = (key: string, fallback = '') => {
    const value = lookup(translations[language], key);
    if (typeof value === 'string') {
      return value;
    }
    const fallbackValue = lookup(translations.en, key);
    return typeof fallbackValue === 'string' ? fallbackValue : fallback || key;
  };

  return (
    <TranslationContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </TranslationContext.Provider>
  );
};

export const useTranslation = () => useContext(TranslationContext);
